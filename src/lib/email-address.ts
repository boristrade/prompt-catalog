/*
  Проверка почтового адреса и исход подписки.

  Отдельным файлом от самого действия по требованию Next: модуль с
  «use server» умеет отдавать наружу только асинхронные функции, а здесь
  нужны обычные — их же вызывает и форма, до отправки. Заодно их можно
  проверить тестами, не поднимая ни базы, ни сервера.
*/

/** Длиннее адресов не бывает: 254 — предел из стандарта. */
export const MAX_EMAIL = 254;

/*
  Проверка нарочно грубая: одна собака, точка после неё, без пробелов.
  Строгие выражения из интернета отвергают настоящие адреса — с плюсом, с
  юникодом, с редкой доменной зоной, — а спасают только от опечаток,
  которые всё равно вскроются первым же письмом. Отказать человеку в
  подписке из-за собственной строгости хуже, чем записать адрес с
  опечаткой.
*/
const EMAIL = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

export function normaliseEmail(raw: string): string {
  return raw.trim().toLowerCase();
}

export function looksLikeEmail(raw: string): boolean {
  const value = normaliseEmail(raw);
  return value.length > 0 && value.length <= MAX_EMAIL && EMAIL.test(value);
}

/*
  Исход подписки одним словом. Фразу подставляет форма из словаря своего
  языка: тащить шесть переводов в серверное действие ради трёх исходов
  незачем.

  «already» — тоже успех с точки зрения человека: он просил писать ему,
  и ему будут писать. Отдельным словом это нужно затем, чтобы не
  обещать письмо, которого не будет: повторного приветствия мы не шлём.
*/
export type SubscribeState =
  | { status: "idle" }
  | { status: "ok" }
  | { status: "already" }
  | { status: "invalid" }
  | { status: "error" };
