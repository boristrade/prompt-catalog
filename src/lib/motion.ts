/*
  Арифметика анимаций — отдельно от компонентов, чтобы её можно было
  проверить тестом. В компоненте эти же строки лежали бы внутри
  requestAnimationFrame, где их не проверить ничем, кроме глаза.
*/

/**
 * Плавное торможение: быстро в начале, мягко в конце.
 *
 * Линейный счётчик читается как загрузка — цифра ползёт с одинаковой
 * скоростью и непонятно, когда остановится. С торможением почти всё
 * число набирается в первую треть времени, а конец только доводит.
 */
export function easeOutCubic(progress: number): number {
  const p = Math.min(Math.max(progress, 0), 1);
  return 1 - Math.pow(1 - p, 3);
}

/**
 * Значение счётчика через `elapsed` мс после старта.
 *
 * Округляем к целому: дробные промежуточные значения в подписи вроде
 * «117 промтов» выглядят как ошибка. Нулевая длительность — сразу
 * итог, иначе получилось бы деление на ноль.
 */
export function countValue(
  target: number,
  elapsed: number,
  duration: number,
): number {
  if (duration <= 0) return target;
  return Math.round(target * easeOutCubic(elapsed / duration));
}
