/*
  Готовые тексты каруселей, разложенные по нишам.

  Это самая частая причина, по которой конструктор закрывают, ничего не
  сделав: человек загрузил фото, увидел пустые поля и не придумал, что
  писать. Готовый набор снимает ровно эту остановку — выбрал нишу,
  выбрал текст, нажал «Применить», дальше правит под себя.

  Тексты написаны под то, что в каруселях действительно сохраняют:
  разбор по шагам, сравнение «было — стало», развенчание мифа, список
  ошибок. Не «вдохновляющие цитаты»: их листают, но не сохраняют, а
  сохранение — главный сигнал для ленты.

  Первый слайд всегда обложка: он и решает, откроют ли карусель вообще.
  Последний — вывод с просьбой сохранить, потому что просьба, сказанная
  вслух, работает заметно лучше молчаливой надежды.
*/

export interface ReadyDeck {
  id: string;
  /** Подпись на кнопке в списке. */
  title: string;
  slides: Slide[];
}

export interface Niche {
  id: string;
  title: string;
  decks: ReadyDeck[];
}

/* Сборщики слайдов — чтобы наборы читались, а не тонули в скобках. */

export function cover(eyebrow: string, title: string, pill: string): Slide {
  return { kind: "cover", eyebrow, title, body: "", code: "", takeaway: pill };
}

export function say(
  eyebrow: string,
  title: string,
  body: string,
  takeaway: string,
): Slide {
  return { kind: "statement", eyebrow, title, body, code: "", takeaway };
}

export function box(
  eyebrow: string,
  title: string,
  code: string,
  takeaway: string,
): Slide {
  return { kind: "prompt", eyebrow, title, body: "", code, takeaway };
}

