"use client";

import { createClient } from "@/lib/supabase/client";
import { isSupabaseConfigured } from "@/lib/supabase/config";

/*
  Отметить, что промт скопировали.

  Считаем нажатия на кнопку копирования — единственное действие, по
  которому видно, что промт забрали, а не просто открыли. Просмотры
  считать бесполезно: страницу открывают и закрывают, а копируют то, чем
  собираются пользоваться.

  Вызов ничего не ждёт и ничего не возвращает. Промт уже в буфере обмена
  — если счётчик не доехал, человеку от этого ни холодно ни жарко, и
  задерживать ради него отклик кнопки нельзя. По той же причине ошибки
  проглатываются молча: сломанный счётчик не должен выглядеть как
  сломанное копирование.

  Прибавляет функция в базе, а не запись в таблицу: писать туда напрямую
  не может никто (см. миграцию 0007), иначе любой желающий выставил бы
  своему промту миллион.

  Один и тот же человек, нажавший кнопку трижды, добавит три. Это
  сознательно: цифра здесь — грубый признак спроса, а не число людей, и
  ради точности заводить учёт «кто уже считался» значит завести слежку
  там, где она не нужна.
*/
export function countCopy(promptId: string): void {
  if (!isSupabaseConfigured() || !promptId) return;

  try {
    void createClient()
      .rpc("bump_prompt_copy", { p_prompt_id: promptId })
      .then(() => undefined, () => undefined);
  } catch {
    // Клиент не создался — молчим: копирование уже произошло.
  }
}
