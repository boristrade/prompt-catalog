/** День последнего пополнения каталога. */
export const LATEST = Object.values(ADDED).sort().at(-1) ?? "";

const EDGE = (() => {
  if (!LATEST) return "";
  const day = new Date(`${LATEST}T00:00:00Z`);
  day.setUTCDate(day.getUTCDate() - BATCH_DAYS);
  return day.toISOString().slice(0, 10);
})();

/** Когда промт появился. Пустая строка — если его нет в таблице. */
export function addedOf(id: string): string {
  return ADDED[id] ?? "";
}

/** Из последнего пополнения ли промт. */
export function isNew(id: string): boolean {
  const day = ADDED[id];
  return Boolean(day && day >= EDGE);
}
