/*
  Заглушка под замком.

  Настоящий текст закрытого промта на клиент не уходит вовсе — его
  вырезает veil в lib/prompts.ts. Здесь лежит вымышленный шаблон: он
  показывает форму промта — роль, вводные, формат ответа, — но ни одной
  строки настоящего текста в разметке не оказывается.

  Размытие поверх — это оформление, а не защита: то, что попало в
  разметку, читается через инструменты разработчика, чем его ни закрой.
  Поэтому заглушка обязана быть выдуманной, а не обрезанным настоящим
  текстом.

  Текст по-английски и одинаковый на всех языках нарочно: он не
  читается, а угадывается по форме, и переводить нечего.
*/
export const VEIL = `Role: {specialist}, {years} years in {niche}.
Task: prepare {deliverable} for {audience}.

Context:
— channel: {channel}
— goal: {goal}
— constraints: {constraints}

Answer format:
1. {first block}
2. {second block}
3. {third block}

Tone: {tone}. Length: {length}.`;

/**
 * Подсвечиваем {переменные} акцентом: сразу видно, что заменять на своё,
 * ещё до чтения текста.
 */
export function highlightVars(text: string) {
  return text.split(/(\{[^{}]*\})/g).map((part, i) =>
    part.startsWith("{") && part.endsWith("}") ? (
      <span key={i} className="text-accent">
        {part}
      </span>
    ) : (
      <span key={i}>{part}</span>
    ),
  );
}
