/*
  Общее для карточки в каталоге и страницы промта. Раньше здесь же жила
  заглушка VEIL — вымышленный шаблон, который обе страницы показывали
  под замком вместо настоящего текста. Теперь под замком видно настоящее
  начало промта (его обрезает veil в lib/prompts.ts), и отдельная
  заглушка не нужна.
*/

/**
 * Подсвечиваем {переменные} акцентом: сразу видно, что заменять на своё,
 * ещё до чтения текста.
 */
export function highlightVars(text: string) {
  return text.split(/(\{[^{}]*\})/g).map((part, i) =>
    part.startsWith("{") && part.endsWith("}") ? (
      <span key={i} className="text-accent">
        {part}
      </span>
    ) : (
      <span key={i}>{part}</span>
    ),
  );
}
