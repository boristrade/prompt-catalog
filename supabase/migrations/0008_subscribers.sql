-- Подписка на пополнения каталога.
-- Выполнить в Supabase: SQL Editor → вставить целиком → Run.

/*
  Адреса тех, кто попросил писать о новых промтах.

  Отдельно от profiles нарочно. Подписка — не аккаунт: человек, пришедший
  из соцсетей, оставляет почту, ничего не заводя и никуда не входя. Свяжи
  мы одно с другим — пришлось бы либо заводить ему аккаунт без спроса,
  либо терять адрес, пока он не зарегистрируется.

  Отписка по токену, а не по адресу: ссылка «отписаться» стоит в каждом
  письме, и по ней приходят не вошедшими. Будь там адрес, любой человек
  мог бы отписать чужую почту, просто подставив её в ссылку.
*/
create table if not exists public.subscribers (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  /* Язык, на котором человек подписался: на нём и писать. */
  locale text not null default 'ru',
  /* Откуда пришёл — подвал, страница пополнений. Видно, что работает. */
  source text,
  token text not null unique
    default encode(gen_random_bytes(24), 'hex'),
  /*
    Задел под подтверждение адреса. Сейчас подписка в один шаг, но
    столбец есть сразу: добавлять его потом — значит либо чинить старые
    строки, либо разбираться, почему у половины людей он пустой.
  */
  confirmed_at timestamptz,
  unsubscribed_at timestamptz,
  created_at timestamptz not null default now()
);

/*
  Кто отписался — остаётся в таблице с отметкой времени, а не удаляется.
  Удали мы строку, тот же адрес подписался бы заново с первой же формы, и
  человек, однажды попросивший не писать, получил бы письмо снова.
*/
create index if not exists subscribers_active_idx
  on public.subscribers (created_at desc)
  where unsubscribed_at is null;

alter table public.subscribers enable row level security;

/*
  Ни одной политики — и это не забывчивость.

  Список адресов не должен читаться ни анонимом, ни вошедшим: с
  публичным ключом его иначе выгрузил бы кто угодно. Пишет и читает
  только сервер, служебным ключом, который в браузер не попадает. RLS без
  политик закрывает таблицу для всех остальных.
*/
revoke all on table public.subscribers from anon, authenticated;
